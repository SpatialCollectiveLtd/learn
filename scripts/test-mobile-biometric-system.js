require('dotenv').config({ path: '.env.local' });
const axios = require('axios');

/**
 * Test Mobile Biometric Attendance System
 * 
 * This script tests the complete mobile biometric attendance workflow:
 * 1. Trainer PIN authentication
 * 2. Challenge generation for biometric registration
 * 3. Mock biometric credential registration
 * 4. Authentication challenge generation
 * 5. Mock biometric attendance verification
 */

// Configuration
const BASE_URL = process.env.NODE_ENV === 'production' 
  ? 'https://learn-youth-platform.vercel.app' 
  : 'http://localhost:3000';

const TEST_STAFF_ID = 'SFEA4111T'; // Fredrick Matasa - has mobile permissions and PIN
const TEST_STAFF_PIN = '2001'; // PIN we set up for this trainer (from previous setup attempt) 
const TEST_YOUTH_ID = 'KAY1604FA'; // Real youth from database (KAY1604FA with attendance history)
const TEST_SESSION_ID = 'TEST_SESSION_' + Date.now();

let authToken = null;

/**
 * Mock WebAuthn response for testing
 * In production, this comes from the browser's WebAuthn API
 */
function createMockWebAuthnResponse(challenge, action = 'authenticate') {
  const challengeBuffer = Buffer.from(challenge);
  
  // Mock credential ID (would be generated by authenticator)
  const credentialId = Buffer.from('test-credential-id-' + Date.now()).toString('base64url');
  
  // Mock client data JSON
  const clientDataJSON = {
    type: action === 'register' ? 'webauthn.create' : 'webauthn.get',
    challenge: challengeBuffer.toString('base64url'),
    origin: BASE_URL
  };

  return {
    id: credentialId,
    rawId: credentialId,
    type: 'public-key',
    response: {
      clientDataJSON: Buffer.from(JSON.stringify(clientDataJSON)).toString('base64'),
      authenticatorData: Buffer.from('mock-authenticator-data').toString('base64'),
      signature: Buffer.from('mock-signature-data').toString('base64'),
      // For registration only
      attestationObject: action === 'register' 
        ? Buffer.from('mock-attestation-object').toString('base64') 
        : undefined
    }
  };
}

async function testPINAuthentication() {
  console.log('🔐 Testing trainer PIN authentication...');
  
  try {
    const response = await axios.post(`${BASE_URL}/api/mobile/pin-auth`, {
      staff_id: TEST_STAFF_ID,
      pin: TEST_STAFF_PIN
    });

    if (response.data.success) {
      authToken = response.data.data.token;
      console.log('✅ PIN authentication successful');
      console.log(`   Token expires: ${response.data.data.session.expires_at}`);
      console.log(`   Staff: ${response.data.data.staff.full_name} (${response.data.data.staff.role})`);
      console.log(`   Today's stats: ${response.data.data.stats.attendances_today} attendances, ${response.data.data.stats.unique_youth_today} unique youth`);
      return true;
    } else {
      console.log('❌ PIN authentication failed:', response.data.message);
      return false;
    }
  } catch (error) {
    console.log('❌ PIN authentication error:', error.response?.data?.message || error.message);
    return false;
  }
}

async function testChallengeGeneration(action = 'register') {
  console.log(`\n🎲 Testing challenge generation for ${action}...`);
  
  try {
    const response = await axios.post(`${BASE_URL}/api/mobile/biometric-challenge`, {
      youth_id: TEST_YOUTH_ID,
      action: action
    }, {
      headers: {
        'Authorization': `Bearer ${authToken}`
      }
    });

    if (response.data.success) {
      console.log('✅ Challenge generated successfully');
      console.log(`   Challenge ID: ${response.data.challengeId}`);
      console.log(`   Youth: ${response.data.youth.full_name} (${response.data.youth.program_type})`);
      
      if (action === 'authenticate' && response.data.allowedCredentials) {
        console.log(`   Allowed credentials: ${response.data.allowedCredentials.length}`);
      }
      
      return {
        challengeId: response.data.challengeId,
        challenge: response.data.challenge,
        youth: response.data.youth
      };
    } else {
      console.log('❌ Challenge generation failed:', response.data.message);
      return null;
    }
  } catch (error) {
    console.log('❌ Challenge generation error:', error.response?.data?.message || error.message);
    return null;
  }
}

async function testBiometricRegistration(challengeData) {
  console.log('\n👆 Testing biometric registration...');
  
  const mockWebAuthnResponse = createMockWebAuthnResponse(challengeData.challenge, 'register');
  
  try {
    const response = await axios.post(`${BASE_URL}/api/mobile/biometric-register`, {
      challengeId: challengeData.challengeId,
      youth_id: TEST_YOUTH_ID,
      webAuthnResponse: mockWebAuthnResponse
    }, {
      headers: {
        'Authorization': `Bearer ${authToken}`
      }
    });

    if (response.data.success) {
      console.log('✅ Biometric registration successful');
      console.log(`   Credential ID: ${response.data.data.credential_id}`);
      console.log(`   Youth: ${response.data.data.youth.full_name}`);
      console.log(`   Registered by: ${response.data.data.registered_by}`);
      return true;
    } else {
      console.log('❌ Biometric registration failed:', response.data.message);
      return false;
    }
  } catch (error) {
    console.log('❌ Biometric registration error:', error.response?.data?.message || error.message);
    return false;
  }
}

async function testBiometricAttendance(challengeData) {
  console.log('\n📋 Testing biometric attendance verification...');
  
  const mockWebAuthnResponse = createMockWebAuthnResponse(challengeData.challenge, 'authenticate');
  const attendanceDate = new Date().toISOString().split('T')[0]; // Today's date
  
  try {
    const response = await axios.post(`${BASE_URL}/api/mobile/biometric-attend`, {
      challengeId: challengeData.challengeId,
      youth_id: TEST_YOUTH_ID,
      webAuthnResponse: mockWebAuthnResponse,
      session_id: TEST_SESSION_ID,
      date: attendanceDate,
      note: 'Test biometric attendance via automation script'
    }, {
      headers: {
        'Authorization': `Bearer ${authToken}`
      }
    });

    if (response.data.success) {
      console.log('✅ Biometric attendance recorded successfully');
      console.log(`   Attendance ID: ${response.data.data.attendance_id}`);
      console.log(`   Youth: ${response.data.data.youth.full_name}`);
      console.log(`   Date: ${response.data.data.attendance_date}`);
      console.log(`   Session: ${response.data.data.session_id}`);
      console.log(`   Verification: ${response.data.data.verification_method}`);
      return true;
    } else {
      console.log('❌ Biometric attendance failed:', response.data.message);
      return false;
    }
  } catch (error) {
    console.log('❌ Biometric attendance error:', error.response?.data?.message || error.message);
    return false;
  }
}

async function runCompleteTest() {
  console.log('🚀 Starting Mobile Biometric Attendance System Test\n');
  console.log(`📍 Base URL: ${BASE_URL}`);
  console.log(`👤 Test Staff: ${TEST_STAFF_ID}`);
  console.log(`👨‍🎓 Test Youth: ${TEST_YOUTH_ID}`);
  console.log(`📅 Test Session: ${TEST_SESSION_ID}\n`);

  let testsPassed = 0;
  let totalTests = 5;

  // Test 1: PIN Authentication
  if (await testPINAuthentication()) {
    testsPassed++;
  }

  if (!authToken) {
    console.log('\n❌ Cannot continue without authentication token');
    process.exit(1);
  }

  // Test 2: Registration Challenge
  const registrationChallenge = await testChallengeGeneration('register');
  if (registrationChallenge) {
    testsPassed++;
  }

  // Test 3: Biometric Registration
  if (registrationChallenge && await testBiometricRegistration(registrationChallenge)) {
    testsPassed++;
  }

  // Test 4: Authentication Challenge
  const authChallenge = await testChallengeGeneration('authenticate');
  if (authChallenge) {
    testsPassed++;
  }

  // Test 5: Biometric Attendance
  if (authChallenge && await testBiometricAttendance(authChallenge)) {
    testsPassed++;
  }

  // Results Summary
  console.log('\n' + '='.repeat(60));
  console.log('🏁 TEST RESULTS SUMMARY');
  console.log('='.repeat(60));
  console.log(`✅ Tests Passed: ${testsPassed}/${totalTests}`);
  console.log(`${testsPassed === totalTests ? '🎉' : '⚠️'} Success Rate: ${Math.round((testsPassed / totalTests) * 100)}%`);
  
  if (testsPassed === totalTests) {
    console.log('\n🎊 All tests passed! Mobile biometric attendance system is working correctly.');
    console.log('\n📱 System is ready for production use:');
    console.log('   • Trainers can authenticate with PIN');
    console.log('   • Youth can register biometric credentials');
    console.log('   • Attendance can be recorded via biometric verification');
    console.log('   • All data is properly stored and audited');
  } else {
    console.log('\n🔧 Some tests failed. Please review the errors above and:');
    console.log('   • Ensure database schema is properly set up');
    console.log('   • Verify test staff member exists and has mobile permissions');
    console.log('   • Check that test youth participant exists');
    console.log('   • Confirm API endpoints are deployed and accessible');
  }

  console.log('\n📚 For more details, check:');
  console.log('   • Database: biometric_credentials, biometric_audit_log tables');
  console.log('   • Logs: auth_logs table for authentication attempts');
  console.log('   • UI: /mobile/biometric-attendance page');
}

// Run the test if called directly
if (require.main === module) {
  runCompleteTest().catch(console.error);
}

module.exports = { runCompleteTest };